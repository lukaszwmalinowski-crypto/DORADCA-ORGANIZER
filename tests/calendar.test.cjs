'use strict';
const assert = require('node:assert/strict');
require('../calendar.js');
const calendar = globalThis.KierunekCalendar;
const action = { id: 'test-1', title: 'Zawody, ścieżki; wybory', date: '2026-10-20', group: 'VIII', owner: 'Doradca', notes: 'Zażółć gęślą jaźń\n'.repeat(20), done: false };
const result = calendar.build([action], {}, new Date('2026-10-20T08:00:00Z'));
assert.ok(result.includes('DTSTART;VALUE=DATE:20261020\r\n'));
assert.ok(result.includes('DTEND;VALUE=DATE:20261021\r\n'));
for (const line of result.split('\r\n')) assert.ok(Buffer.byteLength(line) <= 75);
assert.equal(calendar.utc('2026-07-01', '09:00').toISOString(), '2026-07-01T07:00:00.000Z');
assert.equal(calendar.utc('2026-12-01', '09:00').toISOString(), '2026-12-01T08:00:00.000Z');
assert.throws(() => calendar.utc('2026-03-29', '02:30'));
assert.throws(() => calendar.utc('2026-10-25', '02:30'));
assert.throws(() => calendar.validate({ ...action, startTime: '10:00', endTime: '09:00' }));
assert.throws(() => calendar.validate({ ...action, startTime: '09:00' }));
assert.throws(() => calendar.validate({ ...action, date: '2026-02-30' }));
assert.ok(calendar.build([{ ...action, date: '2028-02-29' }]).includes('DTEND;VALUE=DATE:20280301'));
const timed = calendar.build([{ ...action, startTime: '09:00', endTime: '10:00' }]);
assert.ok(timed.includes('DTSTART:20261020T070000Z'));
assert.ok(timed.includes('DTEND:20261020T080000Z'));
assert.equal(/UID:(.*)/.exec(result)[1], /UID:(.*)/.exec(timed)[1]);
const injected = calendar.build([{ ...action, title: 'Tytuł\r\nBEGIN:VEVENT' }]);
assert.equal(injected.split('\r\n').filter(line => line === 'BEGIN:VEVENT').length, 1);
console.log('OK — eksport ICS: daty, godziny, zmiana czasu, polskie znaki i walidacja.');
